#include <iostream>

int main(){
    // Creamos una variable x con valor inicial 0
    int x = 0;

    // Incremento
    x++; // El incremento es un operador unario que incrementa el valor de dicha variable en 1
    std::cout << x << std::endl;

    // Decremento
    x--; // El decremento es un operador unario que decrementa el valor de la variable en 1
    std::cout << x << std::endl;

    return 0;
}